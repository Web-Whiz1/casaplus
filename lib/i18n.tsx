const DICTS: Record<Lang, Dict> = { ro: RO, en: EN };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string };
const LangCtx = createContext<Ctx>({ lang: 'ro', setLang: () => {}, t: (k) => k });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('ro');
  useEffect(() => {
    const saved = typeof window !== 'undefined' ? (localStorage.getItem('casaplus-lang') as Lang | null) : null;
    if (saved === 'ro' || saved === 'en') setLangState(saved);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== 'undefined') localStorage.setItem('casaplus-lang', l);
  };
  const t = (k: string) => DICTS[lang][k] || k;
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export function useLang() { return useContext(LangCtx); }

export function formatPrice(n: number, currency: string = 'EUR', lang: Lang = 'ro') {
  return new Intl.NumberFormat(lang === 'ro' ? 'ro-RO' : 'en-US', {
    style: 'currency', currency, maximumFractionDigits: 0,
  }).format(n);
}
